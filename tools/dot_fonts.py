"""Writes crates/vo-dots/src/font_data.rs from the X11 misc-fixed 6x10 and 8x13 fonts.

Usage: python3 tools/dot_fonts.py <dir with 6x10-ISO8859-1.pcf.gz and 8x13-ISO8859-1.pcf.gz> <out.rs>
The fonts are in the xorg-fonts-misc package (font-misc-misc). Needs Pillow."""
import sys, gzip, io
from PIL.PcfFontFile import PcfFontFile

RANGES = [(0x20, 0x7F), (0xA0, 0x100)]


def font(path):
    f = PcfFontFile(io.BytesIO(gzip.open(path).read()), "iso8859-1")
    rows_all = []
    w = h = None
    for lo, hi in RANGES:
        for code in range(lo, hi):
            g = f.glyph[code]
            (dx, dy), dst, src, im = g
            w = w or dx
            h = h or (dst[3] - dst[1])
            assert dx == w, (code, dx)
            rows = []
            for y in range(h):
                bits = 0
                for x in range(w):
                    if im and x < im.size[0] and y < im.size[1] and im.getpixel((x, y)):
                        bits |= 0x80 >> x
                rows.append(bits)
            rows_all.extend(rows)
    ascent = -f.glyph[ord("A")][1][1]
    return w, h, ascent, rows_all


def emit(name, w, h, ascent, rows, out):
    out.write("#[rustfmt::skip]\n")
    out.write(f"pub(crate) const {name}: FontData = FontData {{\n")
    out.write(f"    cell_w: {w},\n    cell_h: {h},\n    ascent: {ascent},\n    rows: &[\n")
    per = h
    for i in range(0, len(rows), per):
        out.write("        " + ", ".join(f"0x{r:02x}" for r in rows[i:i + per]) + ",\n")
    out.write("    ],\n};\n\n")


def main(misc_dir, out_path):
    with open(out_path, "w") as out:
        out.write("//! Generated by `tools/dot_fonts.py` from the X11 misc-fixed bitmap fonts 6x10 and 8x13,\n")
        out.write("//! which are in the public domain (\"Public domain font. Share and enjoy.\"). Do not edit by\n")
        out.write("//! hand.\n")
        out.write("//!\n//! Each glyph is `cell_h` rows, one byte per row, the leftmost column in the top bit.\n")
        out.write("//! Glyphs cover U+0020 to U+007E, then U+00A0 to U+00FF, in that order.\n\n")
        out.write("use crate::font::FontData;\n\n")
        for name, file in [("FONT_5X7", "6x10-ISO8859-1.pcf.gz"), ("FONT_7X9", "8x13-ISO8859-1.pcf.gz")]:
            emit(name, *font(f"{misc_dir}/{file}"), out)


main(sys.argv[1], sys.argv[2])
